@torch.inference_mode()
def measure_cold(worker):
    """Actual sequential cold Prefill of a real-weight MLA layer to the cap."""
    import os
    import csv
    from examples.kimi_k3_fp8_kv_validation import load_attention, allocate_cache
    from dlengine.runtime.context.batch import set_batch_context
    import torch.nn.functional as F
    rows=[]
    for tp in (16, 8, 4):
        hf,index=setup(worker,tp)
        attention,norm=load_attention(MODEL,hf,index,3)
        for dtype in ('bfloat16','fp8_e4m3'):
            for length,chunk in [(8192,8192),(131072,8192),(1048576,8192)] + ([(1048576,4096),(1048576,16384)] if tp==16 else []):
                pages=length//64
                cache=allocate_cache(hf,dtype,pages)
                attention.attn_fwd.k_cache=cache
                bt=torch.arange(pages-1,-1,-1,device='cuda',dtype=torch.int32).reshape(1,1,pages)
                torch.manual_seed(8654)
                hidden=F.rms_norm(torch.randn(chunk,hf.hidden_size,device='cuda',dtype=torch.bfloat16),(hf.hidden_size,),norm,hf.rms_norm_eps)
                def step(start,end):
                    pos=torch.arange(start,end,device='cuda',dtype=torch.int64)
                    slots=bt.flatten()[pos//64].long()*64+pos%64
                    set_batch_context(is_prefill=True,
                        cu_seqlens_q=torch.tensor([0,end-start],device='cuda',dtype=torch.int32),
                        cu_seqlens_k=torch.tensor([0,end],device='cuda',dtype=torch.int32),
                        max_seqlen_q=end-start,max_seqlen_k=end,block_tables=bt,slot_mapping=slots)
                    return attention(pos,hidden[:end-start])
                # Warm kernels outside measurement, then wipe cache. Each timed
                # sweep starts from an empty history and appends every chunk.
                step(0,chunk);torch.cuda.synchronize();cache.zero_()
                dist.barrier();baseline=torch.cuda.memory_allocated();torch.cuda.reset_peak_memory_stats()
                a,b=torch.cuda.Event(enable_timing=True),torch.cuda.Event(enable_timing=True)
                import time
                wall=time.perf_counter();a.record()
                for start in range(0,length,chunk): output=step(start,min(start+chunk,length))
                b.record();b.synchronize();wall=time.perf_counter()-wall
                elapsed=a.elapsed_time(b);peak=torch.cuda.max_memory_allocated()-baseline
                assert torch.isfinite(output).all().item()
                # Bounded and unsplit attention must agree for a nonzero,
                # checkpoint-populated long prefix. Only this last chunk is
                # recomputed; graph timing above is unrelated to this check.
                os.environ['DLENGINE_MLA_PREFIX_CHUNK_SIZE']='0'
                reference=step(length-chunk,length)
                os.environ['DLENGINE_MLA_PREFIX_CHUNK_SIZE']='131072'
                bounded=step(length-chunk,length)
                error=((bounded.float()-reference.float()).norm()/reference.float().norm().clamp_min(1e-12)).item()
                assert error < .02, error
                rows.append(dict(rank=worker.rank,tp=tp,dp=16//tp,context=length,chunk=chunk,
                    cache_dtype=dtype,cold_prefill_cuda_ms=elapsed,cold_prefill_wall_ms=wall*1000,
                    dynamic_peak_bytes=peak,cache_bytes=cache.untyped_storage().nbytes(),
                    split_vs_unsplit_relative_l2=error,weights='MLA layer 3',samples=1))
                if worker.rank==0:print('COLD',rows[-1],flush=True)
                del cache,hidden,output,reference,bounded
                attention.attn_fwd.k_cache=None;torch.cuda.empty_cache()
        del attention,norm
    return rows
